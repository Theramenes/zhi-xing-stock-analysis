def resolve_theme(query: str) -> tuple[str | None, dict | None]:
    """解析用户输入→产业链"""
    query = query.strip()
    # 精确匹配
    if query in THEME_CHAINS:
        return query, THEME_CHAINS[query]
    # 别名匹配
    if query in ALIASES:
        name = ALIASES[query]
        return name, THEME_CHAINS[name]
    # 模糊匹配
    for name, chain in THEME_CHAINS.items():
        if name in query or query in name:
            return name, chain
    return None, None


def get_chain_peers(theme_name: str, target_code: str = None) -> list[str]:
    """获取产业链内对标股票代码列表"""
    _, chain = resolve_theme(theme_name)
    if not chain:
        return []
    all_codes = []
    for codes in chain.values():
        all_codes.extend(codes)
    if target_code and target_code in all_codes:
        all_codes.remove(target_code)
    return list(dict.fromkeys(all_codes))  # 去重保持顺序
